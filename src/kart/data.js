export function rollItem(position, random = Math.random) {
  const pool =
    position <= 2
      ? ["shield", "oil", "boost", "magnet", "shield", "boost", "wave"]
      : position <= 5
        ? ["boost", "bolt", "wave", "shield", "oil", "turbo", "magnet", "emp"]
        : [
            "turbo",
            "boost",
            "bolt",
            "emp",
            "turbo",
            "magnet",
            "shield",
            "wave",
          ];
  return pool[Math.min(pool.length - 1, Math.floor(random() * pool.length))];
}
