export function combineStats(car, character) {
  const result = {
    ...car,
    kart: true,
    character: character.id,
  };
  for (const key of ["speed", "accel", "handling", "drift"]) {
    if (car[key] !== undefined && character[key] !== undefined)
      result[key] = car[key] * 0.6 + character[key] * 0.4;
  }
  // 40% character + 60% vehicle for weight affects knockback
  if (car.weight !== undefined && character.weight !== undefined)
    result.weight = Math.round(car.weight * 0.6 + character.weight * 0.4);
  else result.weight = character.weight;
  result.accel += (75 - character.weight) * 0.1;
  return result;
}
